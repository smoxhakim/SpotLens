export interface VerdictContext {
  mtf?: MtfSummary | null;
  confirmation?: ConfirmationResult | null;
  incomplete?: AnalysisShortfall | null;
}

export function classifyVerdict(
  status: TradeStatus,
  reason: string,
  context: VerdictContext = {},
): Branch {
  const agreement = context.mtf?.agreement ?? null;

  if (status === "POTENTIAL_SETUP") return "PASSED";

  if (status === "AVOID") {
    if (reason === "No market data is available for this pair and timeframe.") return "NO_DATA";
    // Both copies of the higher-timeframe veto run before anything else can
    // return AVOID, so the agreement alone identifies them.
    if (agreement === "COUNTER_TREND_BOUNCE") return "HTF_COUNTER_TREND";
    if (agreement === "ALIGNED_BEARISH") return "HTF_BEARISH";
    if (reason.startsWith("The trend is bearish.")) {
      return agreement === "PULLBACK_IN_UPTREND" ? "PULLBACK_IN_UPTREND_VETO" : "ENTRY_TF_BEARISH";
    }
    if (reason.includes("the trade risks more than it stands to make")) return "RR_BELOW_ONE";
    if (reason.startsWith("The setup scores") && reason.includes("Too little of the evidence")) {
      return "SCORE_AVOID_GRADE";
    }
    return "UNCLASSIFIED";
  }

  if (status === "HIGH_RISK") {
    if (reason.startsWith("Risk/reward is only")) return "RR_BELOW_MINIMUM";
    if (reason.startsWith("Only ") && reason.includes("candles of history")) {
      return "INSUFFICIENT_HISTORY";
    }
    if (reason.startsWith("Price is already trading in the resistance zone")) {
      return "PRICE_IN_RESISTANCE";
    }
    return "UNCLASSIFIED";
  }

  // WAIT_FOR_CONFIRMATION
  if (reason.startsWith("No support zone has formed below the current price")) {
    return "NO_ENTRY_ZONE";
  }
  if (reason.startsWith("A structurally sound stop loss cannot be placed")) return "NO_STOP";
  if (reason.startsWith("The levels for this setup do not form a valid long trade")) {
    return "INVALID_LEVELS";
  }
  if (reason.startsWith("No target above the entry zone can be identified")) {
    return "NO_MEASURABLE_REWARD";
  }
  if (context.incomplete && reason === heldForIncompleteData(context.incomplete)) {
    return "HELD_INCOMPLETE_DATA";
  }
  if (/^Price is -?[\d.]+ ATR above the entry zone/.test(reason)) return "PRICE_EXTENDED";
  if (reason.startsWith("The market is ranging rather than trending.")) {
    return "ENTRY_TF_SIDEWAYS";
  }
  if (reason.startsWith("Price has not reached the entry zone")) return "PRICE_NOT_IN_ZONE";
  if (reason.startsWith("There is no resistance zone or prior high far enough above the entry")) {
    return "REWARD_NOT_STRUCTURAL";
  }
  if (reason.includes("Without a clear higher-timeframe direction, wait for one to establish")) {
    return "HTF_MIXED";
  }
  if (reason.startsWith("Price is in the entry zone, but volume is only")) return "VOLUME_THIN";
  if (reason.startsWith("The setup scores") && reason.includes("not enough else agrees")) {
    return "SCORE_WEAK";
  }
  const confirmation = context.confirmation;
  if (confirmation && reason.startsWith(confirmation.explanation)) {
    if (confirmation.status === "CONTRADICTED") return "CONFIRMATION_CONTRADICTED";
    if (confirmation.status === "NOT_PRESENT") return "CONFIRMATION_NOT_PRESENT";
  }
  return "UNCLASSIFIED";
}

export function branchOf(result: AnalysisResult): Branch {
  return classifyVerdict(result.status, result.statusReason, {
    mtf: result.mtf,
    confirmation: result.confirmation,
    incomplete: result.incomplete,
  });
}

// --- analysis results -----------------------------------------------------------

export function zoneOf(zone: PriceZone) {
  return {
    low: n(zone.low),
    high: n(zone.high),
    mid: n(zone.mid),
    kind: zone.kind,
    touches: zone.touches,
    strength: zone.strength,
    flipped: zone.flipped,
    lastTouchIndex: zone.lastTouchIndex,
  };
}

/** Every decision the engine made, and the inputs to them. No prose. */
export function decisionOf(result: AnalysisResult) {
  const { read, setup, score, confirmation, mtf } = result;
  const { trend } = read;

  return {
    status: result.status,
    incomplete: result.incomplete
      ? `${result.incomplete.scope}:${result.incomplete.timeframe}:${result.incomplete.gap}`
      : null,
    candles: read.candleCount,
    insufficientData: read.insufficientData,
    price: n(read.price),
    atr: n(read.indicators.atr14),
    ema: [n(read.indicators.ema20), n(read.indicators.ema50), n(read.indicators.ema200)],
    rsi: n(read.rsi.value),
    volume: read.volume.read
      ? {
          relative: n(read.volume.read.relative),
          trend: read.volume.read.trend,
          aboveAverage: read.volume.read.isAboveAverage,
        }
      : null,
    trend: `${trend.trend}/${trend.confidence}${trend.conflict ? "/conflict" : ""}`,
    structure: `${trend.structure.structure}:${trend.structure.labels.high ?? "-"}/${trend.structure.labels.low ?? "-"}`,
    emaAlignment: trend.ema.alignment,
    mtf: mtf ? `${mtf.higherTrend}>${mtf.lowerTrend}:${mtf.agreement}` : null,
    support: read.support.map(zoneOf),
    resistance: read.resistance.map(zoneOf),
    setup: setup
      ? {
          entry: {
            low: n(setup.entry.low),
            high: n(setup.entry.high),
            mid: n(setup.entry.mid),
            inZone: setup.entry.priceInZone,
            distanceAtr: n(setup.entry.distanceAtr),
          },
          stop: {
            price: n(setup.stopLoss.price),
            riskPct: n(setup.stopLoss.riskPct),
            atrMultiple: n(setup.stopLoss.atrMultiple),
          },
          targets: setup.takeProfits.map((t) => ({
            label: t.label,
            level: n(t.level),
            rr: n(t.rr),
            kind: t.kind,
          })),
          riskReward: {
            ratio: n(setup.riskReward.ratio),
            risk: n(setup.riskReward.risk),
            reward: n(setup.riskReward.reward),
            measuredTo: setup.riskReward.measuredTo,
            isSynthetic: setup.riskReward.isSynthetic,
            isPoor: setup.riskReward.isPoor,
          },
        }
      : null,
    score: score
      ? {
          total: score.total,
          grade: score.grade,
          breakdown: Object.fromEntries(
            Object.entries(score.breakdown).map(([key, category]) => [key, n(category.score)]),
          ),
        }
      : null,
    confirmation: confirmation
      ? {
          status: confirmation.status,
          evaluatedAt: confirmation.evaluatedAt,
          signals: confirmation.signals.map((s) => `${s.type}:${s.signal}`),
          invalidates: confirmation.invalidationReason !== null,
        }
      : null,
  };
}

/**
 * The prose. `full` adds every reason the result carries; without it, only the
 * verdict's own reason and the confirmation explanation — enough for the long
 * prefix sweeps without making the file unreadable.
 */
export function wordingOf(result: AnalysisResult, full: boolean) {
  const { read, setup, score, confirmation, mtf } = result;
  const core = {
    statusReason: result.statusReason,
    confirmation: confirmation?.explanation ?? null,
  };
  if (!full) return core;

  return {
    ...core,
    mtfNote: mtf?.note ?? null,
    mtfConflictNote: mtf?.conflictNote ?? null,
    trend: read.trend.reason,
    zones: read.zonesReason,
    zoneWidth: read.zoneWidthNote,
    volume: read.volume.reason,
    rsi: read.rsi.reason,
    entry: setup?.entry.reason ?? null,
    checklist: setup?.entry.confirmations ?? null,
    stop: setup?.stopLoss.reason ?? null,
    riskReward: setup?.riskReward.reason ?? null,
    targets: setup?.takeProfits.map((t) => `${t.label}: ${t.reason}`) ?? null,
    score: score
      ? Object.fromEntries(Object.entries(score.breakdown).map(([key, c]) => [key, c.reason]))
      : null,
    signals:
      confirmation?.signals.map((s) => `${s.type}:${s.signal}: ${s.title} — ${s.detail}`) ?? null,
    invalidation: confirmation?.invalidationReason ?? null,
  };
}

/** The structured explanation list, as id, signal and title. */
export function explanationsOf(result: AnalysisResult): string[] {
  return buildExplanations(result).map((e) => `${e.id}|${e.signal}|${e.title}`);
}

// --- lifecycle plans --------------------------------------------------------------

function payloadOf(payload: ConfirmationPayload | null) {
  return payload
    ? {
        status: payload.status,
        evaluatedAt: payload.evaluatedAt,
        signals: payload.signals.map((s) => `${s.type}:${s.signal}`),
      }
    : null;
}

function createOf(create: PlannedCreate) {
  const { snapshot } = create;
  return {
    status: create.status,
    origin: [n(create.origin.zoneLow), n(create.origin.zoneHigh)],
    marksConfirmed: create.marksConfirmed,
    event: create.event.type,
    payload: payloadOf(create.event.payload),
    snapshot: {
      entry: [n(snapshot.entryLow), n(snapshot.entryHigh)],
      stop: n(snapshot.stopLoss),
      targets: [n(snapshot.takeProfit1), n(snapshot.takeProfit2), n(snapshot.takeProfit3)],
      riskReward: n(snapshot.riskReward),
      riskRewardIsSynthetic: snapshot.riskRewardIsSynthetic,
      score: snapshot.score,
      scoreGrade: snapshot.scoreGrade,
      analysisStatus: snapshot.analysisStatus,
      trend: snapshot.detail.trend,
      mtfAgreement: snapshot.detail.mtfAgreement,
      createdFromCandleTime: snapshot.detail.createdFromCandleTime,
      regime: snapshot.detail.regime,
      ladder: snapshot.detail.takeProfits.map((t) => [t.label, n(t.level), n(t.rr), t.kind]),
      breakdown: Object.fromEntries(
        Object.entries(snapshot.detail.scoreBreakdown).map(([key, c]) => [key, n(c.score)]),
      ),
    },
  };
}

function transitionOf(transition: PlannedTransition) {
  return {
    setupId: transition.setupId,
    from: transition.from,
    to: transition.to,
    event: transition.event.type,
    marksConfirmed: transition.marksConfirmed,
    invalidates: transition.invalidationReason !== null,
    payload: payloadOf(transition.event.payload),
  };
}

export function planDecisionOf(plan: SetupPlan) {
  switch (plan.action) {
    case "NONE":
      return { action: plan.action, cause: plan.cause };
    case "CREATE":
      return { action: plan.action, create: createOf(plan.create) };
    case "TRANSITION":
      return { action: plan.action, transition: transitionOf(plan.transition) };
    case "REPLACE":
      return {
        action: plan.action,
        invalidate: transitionOf(plan.invalidate),
        create: createOf(plan.create),
      };
  }
}

/** The prose a plan would write into `SetupEvent` and `TrackedSetup` rows. */
export function planWordingOf(plan: SetupPlan) {
  switch (plan.action) {
    case "NONE":
      return { reason: plan.reason };
    case "CREATE":
      return {
        detail: plan.create.event.detail,
        statusReason: plan.create.snapshot.detail.statusReason,
        explanation: plan.create.event.payload?.explanation ?? null,
      };
    case "TRANSITION":
      return {
        detail: plan.transition.event.detail,
        invalidationReason: plan.transition.invalidationReason,
        explanation: plan.transition.event.payload?.explanation ?? null,
      };
    case "REPLACE":
      return {
        invalidateDetail: plan.invalidate.event.detail,
        invalidationReason: plan.invalidate.invalidationReason,
        createDetail: plan.create.event.detail,
        explanation: plan.create.event.payload?.explanation ?? null,
      };
  }
}
