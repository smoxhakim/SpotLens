/**
 * Projections for the golden-master baseline (Phase 5, commit 0).
 *
 * A golden file is only useful if a diff in it means something, so every
 * projection here keeps two things apart:
 *
 *   - **decisions** — statuses, levels, ratios, scores, confirmation verdicts and
 *     lifecycle plans. Commit 1 (diagnostics) and commit 2 (wording) must leave
 *     every one of these byte-identical.
 *   - **wording** — the reasons and explanations. Commit 1 must leave these
 *     identical too; commit 2 is allowed to change only the ones it lists.
 *
 * Numbers are rounded to twelve significant digits. That absorbs a last-bit
 * difference between Node versions in `Math.exp` and friends, while any real
 * change to a level, a ratio or a score is still many orders of magnitude
 * larger than the rounding.
 *
 * Test code only — nothing in the application imports this file.
 */

export type Num = number | string | null;

export function n(value: number | null | undefined): Num {
  if (value === null || value === undefined) return null;
  if (Number.isNaN(value)) return "NaN";
  if (!Number.isFinite(value)) return value > 0 ? "Infinity" : "-Infinity";
  if (Object.is(value, -0)) return 0;
  return Number(value.toPrecision(12));
}

/** One line per case: an id, a tab, and the projection as compact JSON. */
export function line(id: string, value: unknown): string {
  return `${id}\t${JSON.stringify(value)}`;
}

/** A golden file's full text: a short header, then one line per case. */
export function goldenFile(title: string, lines: string[]): string {
  return [
    `# ${title}`,
    "# Golden-master baseline (Phase 5, commit 0). Generated by the tests in lib/golden.",
    "# A diff in this file is a change in behaviour. Review it; never update it blindly.",
    ...lines,
    "",
  ].join("\n");
}

